"""Generate skill/ycgrid-python/references/mcp-tools.md from mcp/tools.json.

Usage:
    python gen_tools_doc.py [tools.json] [output.md]
By default reads tools.json next to this file and writes ../skill/ycgrid-python/references/mcp-tools.md.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "tools.json"
DST = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parent / "skill" / "ycgrid-python" / "references" / "mcp-tools.md"

HEADER = """# YCGrid MCP tool reference

> Generated by `mcp/gen_tools_doc.py` from `mcp/tools.json`; do not edit by hand.

## Ground rules

- Getting started: `yc_connect` -> `yc_get_workbook_info`; the project entry point is `main.py`.
- Before writing code: confirm the API really exists with `yc_api_lookup`.
- After changing `.py` files: `yc_reload_python` -> `yc_python_status` (check the registrations) -> test -> `yc_read_console`.
- How to test:
  - macros: `yc_run_macro`.
  - buttons and combo boxes: `yc_trigger_control`.
  - per-cell OnChange: write the target cell with `yc_write_range`, or use `yc_ui_input`.
  - sheet events (Change, SelectionChange, double-click, shortcuts): `yc_ui_input`.
  - UDFs and formulas: `yc_evaluate_formula`.
  - market data events and formulas: push with `yc_topics`.
- Checking results: values with `yc_read_range`; styles and the dependency tree with `yc_inspect_cells`; the look with `yc_screenshot` (scroll there first with `yc_scroll_view` if needed).
- Operations without a dedicated tool (conditional formatting, data validation, defined names...): use the object model through `yc_exec_python`, or run a UI command with `yc_execute_command`.
- Missing Python packages: `yc_install_packages` (installed into the project's own runtime, the system Python is not touched).
- Tools marked "runs user code" may trigger real trades: without the user's consent, never use them on macros, controls or events related to placing orders or changing positions.

## Common output

- The first line is the conclusion; large results are truncated with a hint on how to get the next page.
- Results are text (JSON for structured results; `yc_screenshot` returns an image).
- On failure `isError=true` and the text says what went wrong and what to do: `Invalid arguments: ...` for a wrong
  parameter, a tool's own message (an unknown sheet lists the sheets; `confirm=true` / `discard_changes=true` when an
  action needs them), `YCGrid reported an error: ...` for an error from YCGrid (its message; `yc.YcError.Code` in
  Python: `E_ARG`, `E_NOT_FOUND`, `E_APP`, `E_FORMULA`, `E_PROTECTED`, `E_PASSWORD`, `E_UNSUPPORTED` (not implemented
  yet), `E_TIMEOUT`...), or `The connection to YCGrid was lost` (start YCGrid, then `yc_connect`).
"""

TYPE_NAMES = {"string": "string", "integer": "integer", "number": "number", "boolean": "boolean", "object": "object", "array": "array", "null": "null"}


def type_label(sch: dict) -> str:
    t = sch.get("type")
    if isinstance(t, list):
        return " / ".join(TYPE_NAMES.get(x, x) for x in t)
    if t == "array":
        return f"array of {type_label(sch.get('items', {}))}"
    label = TYPE_NAMES.get(t, str(t))
    lo, hi = sch.get("minimum"), sch.get("maximum")
    if lo is not None or hi is not None:
        label += f" ({'' if lo is None else lo}-{'' if hi is None else hi})"
    return label


def enum_text(sch: dict) -> str:
    vals = sch.get("enum") or sch.get("items", {}).get("enum")
    return "One of: " + ", ".join(f"`{v}`" for v in vals) + "." if vals else ""


def esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def rows(props: dict, required: list[str], prefix: str = ""):
    for name, sch in props.items():
        full = f"{prefix}{name}"
        default = json.dumps(sch["default"], ensure_ascii=False) if "default" in sch else ""
        desc = "".join(x for x in (sch.get("description", ""), enum_text(sch)) if x)
        yield f"| `{full}` | {esc(type_label(sch))} | {'✓' if name in required else ''} | {esc(default)} | {esc(desc)} |"
        if sch.get("type") == "object" and "properties" in sch:
            yield from rows(sch["properties"], sch.get("required", []), f"{full}.")
        items = sch.get("items", {})
        if sch.get("type") == "array" and items.get("type") == "object":
            yield from rows(items["properties"], items.get("required", []), f"{full}[].")


def nature(a: dict) -> str:
    if a.get("readOnlyHint"):
        parts = ["read-only"]
    else:
        parts = ["modifies the workbook or state"]
        if a.get("destructiveHint", True):
            parts.append("may overwrite or delete")
        if a.get("idempotentHint"):
            parts.append("idempotent")
    if a.get("openWorldHint", True):
        parts.append("runs user code")
    return ", ".join(parts)


def main() -> None:
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    tools = doc["tools"]
    out = [HEADER, "## Tool overview", "", "| Group | Tool | Purpose | Nature | Milestone |", "|---|---|---|---|---|"]
    for t in tools:
        m = t.get("_meta", {})
        out.append(f"| {m.get('ycgrid/group', '')} | `{t['name']}` | {t['title']} | {nature(t['annotations'])} | {m.get('ycgrid/milestone', '')} |")
    out += ["", "## Tools", ""]
    for t in tools:
        sch = t["inputSchema"]
        m = t.get("_meta", {})
        out += [f"### `{t['name']}` — {t['title']}", "",
                f"Nature: {nature(t['annotations'])} | Milestone: {m.get('ycgrid/milestone', '')}", "",
                t["description"], ""]
        if sch.get("properties"):
            out += ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"]
            out += list(rows(sch["properties"], sch.get("required", [])))
        else:
            out.append("(no parameters)")
        out.append("")
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {DST} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
