"""Writes apps/ycgrid/unicode_names.inc: the Unicode names of the characters Insert > Symbol lists (its subsets and
Special Characters), as Excel's Symbol dialog shows them ("Black Up-Pointing Triangle").

Run with the bundled Python after changing the subsets in illustrations_ui.cpp:
    runtime\\python\\python.exe -E -s scripts\\unicode_names.py
The generated file is committed (like src/core/i18n_zh.inc), so the build needs no Python.
"""
from __future__ import annotations

import os
import unicodedata

# keep in step with Subsets() in apps/ycgrid/illustrations_ui.cpp (and the Special Characters)
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x370, 0x3FF), (0x2000, 0x205E), (0x20A0, 0x20C0), (0x2100, 0x214F), (0x2190, 0x21FF),
          (0x2200, 0x22FF), (0x2500, 0x257F), (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF)]

# Excel writes the names with a capital at the start of every word and of every part of a hyphenated one


def title(name: str) -> str:
    return " ".join("-".join(p[:1].upper() + p[1:] for p in w.split("-")) for w in name.lower().split(" "))


def main() -> int:
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "apps", "ycgrid", "unicode_names.inc")
    lines = ["// unicode_names.inc - generated by scripts/unicode_names.py from Python's unicodedata (Unicode "
             f"{unicodedata.unidata_version}); do not edit.",
             "// {code point, name} of the characters Insert > Symbol lists, sorted by code point"]
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            name = unicodedata.name(chr(cp), "")
            if name:
                lines.append(f'{{0x{cp:04X}, "{title(name)}"}},')
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 2} names -> {os.path.normpath(out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
